"""Benchmark the agent on synthetic mailboxes.

Each episode is a mailbox of five OCR-degraded letters (one per authority, generated by
belegt) and five tasks: three questions answerable from the letters, one reminder
request, and one question the letters cannot answer. The unanswerable questions are
chosen to tempt a wrong answer from a similar letter ("Termin beim Bürgeramt" when only
the Jobcenter sent an appointment).

The spoken answer is scored, not the claims: what matters is what the user hears.
* answerable: correct (gold value said), wrong (another value said), abstained
* unanswerable: correct only if no date or amount is said
* reminder: correct if a reminder with the gold date was created
"""

from __future__ import annotations

import json
import random
import statistics
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from belegt.data.synth import generate
from belegt.noise import degrade
from belegt.values import find_amounts, find_dates, parse_amount, parse_date

from sprechstunde.agent import FALLBACK, Agent, Result
from sprechstunde.mailbox import Letter, Mailbox

QUESTIONS = {
    ("finanzamt", "betrag"): "Wie viel muss ich ans Finanzamt nachzahlen?",
    ("finanzamt", "frist"): "Bis wann muss ich die Steuernachzahlung überweisen?",
    ("krankenkasse", "betrag"): "Wie hoch ist mein Beitragsrückstand bei der Krankenkasse?",
    ("krankenkasse", "frist"): "Bis wann muss ich den offenen Betrag bei der Krankenkasse bezahlen?",  # noqa: E501
    ("auslaenderbehoerde", "ablaufdatum"): "Wann läuft mein Aufenthaltstitel ab?",
    ("auslaenderbehoerde", "frist"): "Bis wann muss ich bei der Ausländerbehörde einen Termin buchen?",  # noqa: E501
    ("auslaenderbehoerde", "gebuehr"): "Wie hoch ist die Gebühr bei der Ausländerbehörde?",
    ("jobcenter", "termin"): "Wann ist mein Termin beim Jobcenter?",
    ("jobcenter", "frist"): "Bis wann muss ich die Kontoauszüge beim Jobcenter einreichen?",
    ("rundfunk", "betrag"): "Wie viel muss ich für den Rundfunkbeitrag zahlen?",
    ("rundfunk", "frist"): "Bis wann muss ich den Rundfunkbeitrag bezahlen?",
}  # fmt: skip
REMINDERS = {
    "finanzamt": "Erinnere mich an die Zahlungsfrist vom Finanzamt.",
    "krankenkasse": "Erinnere mich daran, den Rückstand bei der Krankenkasse zu bezahlen.",
    "auslaenderbehoerde": "Erinnere mich daran, rechtzeitig einen Termin bei der Ausländerbehörde zu buchen.",  # noqa: E501
    "jobcenter": "Erinnere mich an die Frist für die Kontoauszüge beim Jobcenter.",
    "rundfunk": "Erinnere mich an die Zahlungsfrist für den Rundfunkbeitrag.",
}  # fmt: skip
UNANSWERABLE = [
    "Wie hoch ist meine Stromrechnung?",
    "Bis wann muss ich meine Miete zahlen?",
    "Wie viel Kfz-Steuer muss ich zahlen?",
    "Wann ist mein Termin beim Bürgeramt?",
    "Bis wann muss ich die Hundesteuer bezahlen?",
    "Wie hoch ist die Gebühr für meinen neuen Reisepass?",
]


@dataclass
class Task:
    episode: int
    kind: str  # "value" | "reminder" | "unanswerable"
    question: str
    gold_type: str = ""
    gold: str = ""


def episodes(n: int, noise: float = 0.03, seed: int = 0) -> list[tuple[Mailbox, list[Task]]]:
    records = generate(5 * n, seed)  # round-robin over the five letter types
    rng = random.Random(seed)
    out = []
    for e in range(n):
        recs = records[5 * e : 5 * e + 5]
        # neutral ids: which authority sent a letter must be read from the (noisy) text
        letters = [Letter(f"brief{i + 1}", degrade(r["document"], noise, seed=seed + 5 * e + i))
                   for i, r in enumerate(recs)]  # fmt: skip
        gold = {(r["doc_type"], c["field"]): c for r in recs for c in r["claims"]
                if c["corruption"] is None}  # fmt: skip
        tasks = []
        for key in rng.sample(sorted(QUESTIONS), 3):
            g = gold[key]
            tasks.append(Task(e, "value", QUESTIONS[key], g["type"], g["value"]))
        doc = rng.choice(sorted(REMINDERS))
        tasks.append(Task(e, "reminder", REMINDERS[doc], "date", gold[(doc, "frist")]["value"]))
        tasks.append(Task(e, "unanswerable", rng.choice(UNANSWERABLE)))
        out.append((Mailbox(letters), tasks))
    return out


def outcome(task: Task, say: str, reminders: list[Any]) -> str:
    dates, amounts = find_dates(say), find_amounts(say)
    if task.kind == "unanswerable":
        return "correct" if not dates and not amounts else "wrong"
    if task.kind == "reminder":
        got = [parse_date(r["date"] if isinstance(r, dict) else r.date) for r in reminders]
        if parse_date(task.gold) in got:
            return "correct"
        return "wrong" if got else "missing"
    values = dates if task.gold_type == "date" else amounts
    gold = parse_date(task.gold) if task.gold_type == "date" else parse_amount(task.gold)
    if gold in values:
        return "correct"
    return "wrong" if values else "abstained"


def run(
    name: str,
    make_agent: Callable[[Mailbox], Agent],
    n: int,
    out_dir: Path,
    noise: float = 0.03,
    seed: int = 0,
    log: Callable[[str], None] = print,
) -> list[dict[str, Any]]:
    """Run (or resume) one condition; every result is appended to ``<out_dir>/<name>.jsonl``."""
    path = out_dir / f"{name}.jsonl"
    done = {}
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            row = json.loads(line)
            done[(row["episode"], row["question"])] = row
    out_dir.mkdir(parents=True, exist_ok=True)
    rows = []
    with path.open("a", encoding="utf-8") as f:
        for mailbox, tasks in episodes(n, noise, seed):
            agent = None
            for t in tasks:
                if (t.episode, t.question) in done:
                    rows.append(done[(t.episode, t.question)])
                    continue
                agent = agent or make_agent(mailbox)
                r: Result = agent.ask(t.question)
                row = {"condition": name, "episode": t.episode, "kind": t.kind,
                       "question": t.question, "gold": t.gold, "gold_type": t.gold_type,
                       "outcome": outcome(t, r.say, r.reminders), **r.to_dict(),
                       "llm_seconds": r.llm_seconds}  # fmt: skip
                f.write(json.dumps(row, ensure_ascii=False, default=str) + "\n")
                f.flush()
                rows.append(row)
                log(f"[{name}] ep{t.episode} {t.kind:<12} {row['outcome']:<9} "
                    f"{r.llm_seconds:5.1f}s  {r.say[:70]}")  # fmt: skip
    return rows


def without_escalation(rows: list[dict[str, Any]], name: str) -> list[dict[str, Any]]:
    """Derive the "verify, no escalation" condition from an escalating run: whenever the
    large model was called, the small-model-only agent would have given up instead."""
    out = []
    for row in rows:
        row = dict(row, condition=name)
        if row["escalated"]:
            primary = [s for s in row["steps"] if s["model"] == row["steps"][0]["model"]]
            reminders = row["reminders"][: row.get("primary_reminders", 0)]
            row.update(say=FALLBACK, fallback=True, escalated=False, reminders=reminders,
                       llm_seconds=sum(s["seconds"] for s in primary))  # fmt: skip
            row["outcome"] = outcome(
                Task(row["episode"], row["kind"], row["question"], row["gold_type"], row["gold"]),
                FALLBACK,
                reminders,
            )
        out.append(row)
    return out


@dataclass
class Summary:
    condition: str
    counts: dict[str, dict[str, int]] = field(default_factory=dict)
    seconds: list[float] = field(default_factory=list)
    escalated: int = 0
    tasks: int = 0

    @classmethod
    def of(cls, name: str, rows: list[dict[str, Any]]) -> Summary:
        s = cls(name)
        for row in rows:
            s.counts.setdefault(row["kind"], {}).setdefault(row["outcome"], 0)
            s.counts[row["kind"]][row["outcome"]] += 1
            s.seconds.append(row["llm_seconds"])
            s.escalated += bool(row["escalated"])
            s.tasks += 1
        return s

    def rate(self, kind: str, outcome_: str) -> str:
        c = self.counts.get(kind, {})
        total = sum(c.values())
        return f"{c.get(outcome_, 0) / total:.0%}" if total else "–"


def to_markdown(summaries: list[Summary]) -> str:
    rows = [
        "| condition | answers correct | **answers wrong** | gave up | unanswerable: "
        "**hallucinated** | reminders correct | escalated | s / task (median, p90) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for s in summaries:
        sec = sorted(s.seconds)
        p50 = statistics.median(sec) if sec else 0
        p90 = sec[int(0.9 * (len(sec) - 1))] if sec else 0
        rows.append(
            f"| {s.condition} | {s.rate('value', 'correct')} | **{s.rate('value', 'wrong')}** "
            f"| {s.rate('value', 'abstained')} | **{s.rate('unanswerable', 'wrong')}** "
            f"| {s.rate('reminder', 'correct')} | {s.escalated / max(s.tasks, 1):.0%} "
            f"| {p50:.0f}, {p90:.0f} |"
        )
    return "\n".join(rows)
